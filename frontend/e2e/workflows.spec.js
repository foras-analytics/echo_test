test('timeline reserves exactly the visible lane rows across channel selections', async ({ page }) => {
  await importData(page, [...dataset, { name: 'Other 2', messages: [] }])
  await explorer(page)
  const channels = ['Channel A', 'Channel B', 'Empty', 'Other 2']
  const cases = [
    { divider: 2, selected: [0], lanes: 1 },
    { divider: 2, selected: [0, 1], lanes: 2 },
    { divider: 2, selected: [2], lanes: 1 },
    { divider: 2, selected: [2, 3], lanes: 1 },
    { divider: 2, selected: [0, 2], lanes: 2 },
    { divider: 2, selected: [0, 1, 2, 3], lanes: 3 },
    { divider: 2, selected: [], lanes: 0 },
    { divider: 0, selected: [0, 1, 2, 3], lanes: 1 },
    { divider: 4, selected: [0, 1, 2, 3], lanes: 4 },
    { divider: 4, selected: [3], lanes: 1 },
  ]
  for (const entry of cases) {
    await page.getByLabel('Individual lanes').fill(String(entry.divider))
    for (let i = 0; i < channels.length; i++) {
      await page.getByLabel(`Channel ${channels[i]}`, { exact: true }).setChecked(entry.selected.includes(i))
    }
    await expect(page.locator('.lane-label')).toHaveCount(entry.lanes)
    await expect.poll(() => page.evaluate(() => {
      const labels = [...document.querySelectorAll('.lane-label')]
      const canvas = document.querySelector('canvas').getBoundingClientRect()
      const panel = document.querySelector('.timeline-panel').getBoundingClientRect()
      if (!labels.length) return canvas.height <= 24 && panel.bottom - canvas.bottom <= 12
      const last = labels.at(-1).getBoundingClientRect()
      return Math.abs(canvas.bottom - last.bottom) < 1 && panel.bottom - canvas.bottom <= 12
    }), { message: `Unused timeline row for divider ${entry.divider}, selected ${entry.selected}` }).toBe(true)
    await expect.poll(() => page.locator('.timeline-scroll').evaluate(el => el.scrollHeight <= el.clientHeight)).toBe(true)
  }
})
