test('viewport shading excludes context-only rows and context size updates live groups', async ({ page }) => {
  const longContext = structuredClone(dataset)
  longContext.forEach(c => c.messages.forEach(m => {
    if (!/alpha/i.test(m.subject + m.messageText)) m.messageText = Array(25).fill('Surrounding conversation. Plain text on a separate line.').join('\n')
  }))
  await importData(page, longContext)
  await addKeyword(page, 'Alpha')
  await explorer(page)
  await page.locator('.keyword-chip', { hasText: 'Alpha' }).click()
  await expect(page.locator('.results-toolbar')).toContainText('6 messages')
  await page.getByRole('button', { name: 'Open context for m0-3', exact: true }).click()
  await page.getByTestId('message-scroll').evaluate(el => { el.scrollTop = 0 })
  await expect(page.locator('[data-message-id="m0-0"]')).toBeVisible()
  await expect.poll(() => page.locator('.timeline-panel').getAttribute('data-visible-start')).toBeNull()
  await expect(page.locator('.timeline-toolbar')).toContainText('6 messages')
  await page.locator('[data-message-id="m0-3"]').scrollIntoViewIfNeeded()
  await expect.poll(async () => page.evaluate(() => {
    const box = document.querySelector('.message-scroll').getBoundingClientRect()
    const primaryTimes = [...document.querySelectorAll('[data-message-id][data-primary="true"]')].filter(el => {
      const r = el.getBoundingClientRect(); return r.bottom > box.top + 1 && r.top < box.bottom - 1
    }).map(el => Date.parse(el.querySelector('time').dateTime))
    const panel = document.querySelector('.timeline-panel')
    return primaryTimes.length > 0 && Math.abs(Number(panel.dataset.visibleStart) - Math.min(...primaryTimes)) < 1 && Math.abs(Number(panel.dataset.visibleEnd) - Math.max(...primaryTimes)) < 1
  })).toBe(true)
  const bound = await page.getByLabel('Start, inclusive').inputValue()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Context neighbors on each side' }).fill('1')
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.locator('[data-message-id="m0-0"]')).toHaveCount(0)
  await expect(page.locator('.in-context')).toHaveCount(3)
  await expect(page.getByLabel('Start, inclusive')).toHaveValue(bound)
})

